-- Auth's outbox, for sealed email requests. The same shape as Event's and
-- Ticketing's, because one relay binary drains all three.

-- CreateTable
CREATE TABLE "OutboxMessage" (
    "id" TEXT NOT NULL,
    "tenantId" TEXT NOT NULL,
    "seq" BIGSERIAL NOT NULL,
    "topic" TEXT NOT NULL,
    "eventType" TEXT NOT NULL,
    "schemaVersion" INTEGER NOT NULL DEFAULT 1,
    "aggregateId" TEXT NOT NULL,
    "payload" JSONB NOT NULL,
    "publishedAt" TIMESTAMP(3),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "attempts" INTEGER NOT NULL DEFAULT 0,
    "lastError" TEXT,
    "nextAttemptAt" TIMESTAMP(3),
    "deadLetteredAt" TIMESTAMP(3),

    CONSTRAINT "OutboxMessage_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE INDEX "OutboxMessage_tenantId_idx" ON "OutboxMessage"("tenantId");

-- ===========================================================================
-- Everything below is hand-written. Prisma emits neither row-level security nor
-- partial indexes.
-- ===========================================================================

-- The drain's index: undelivered rows in seq order, emptying itself as they
-- publish. Event's harden_outbox migration explains why it must be partial.
CREATE INDEX "OutboxMessage_undelivered_idx"
  ON "OutboxMessage" ("seq")
  WHERE "publishedAt" IS NULL AND "deadLetteredAt" IS NULL;

-- The prune's index, the mirror image of the drain's.
CREATE INDEX "OutboxMessage_prunable_idx"
  ON "OutboxMessage" ("publishedAt")
  WHERE "publishedAt" IS NOT NULL AND "deadLetteredAt" IS NULL;

-- The per-aggregate ordering guard's index. It holds only rows waiting out a retry
-- backoff, which is normally none.
CREATE INDEX "OutboxMessage_backoff_idx"
  ON "OutboxMessage" ("tenantId", "aggregateId", "topic", "seq")
  WHERE "publishedAt" IS NULL
    AND "deadLetteredAt" IS NULL
    AND "nextAttemptAt" IS NOT NULL;

-- The service inserts a message in the transaction that issues the reset, and
-- selects only because Prisma's create reads the new row back. It never updates
-- or deletes one: delivery state belongs to the relay.
GRANT SELECT, INSERT ON "OutboxMessage" TO eventhub_auth_app;
GRANT USAGE, SELECT ON SEQUENCE "OutboxMessage_seq_seq" TO eventhub_auth_app;

-- The relay reads rows, marks delivery state and prunes. Its UPDATE is limited to
-- those columns, so it cannot rewrite tenantId or payload.
GRANT SELECT ON "OutboxMessage" TO eventhub_auth_relay;
GRANT UPDATE ("publishedAt", "attempts", "lastError", "nextAttemptAt", "deadLetteredAt")
  ON "OutboxMessage" TO eventhub_auth_relay;
GRANT DELETE ON "OutboxMessage" TO eventhub_auth_relay;

ALTER TABLE "OutboxMessage" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "OutboxMessage" FORCE  ROW LEVEL SECURITY;

-- Two readers, two policies, as in Event and Ticketing. The service sees its own
-- tenant; the relay drains by delivery state across every tenant.
CREATE POLICY outbox_tenant ON "OutboxMessage" TO eventhub_auth_app
  USING ("tenantId" = current_setting('app.tenant_id', true))
  WITH CHECK ("tenantId" = current_setting('app.tenant_id', true));

CREATE POLICY outbox_relay ON "OutboxMessage" TO eventhub_auth_relay
  USING (true);

-- This database's RLS migration says no unique index may omit tenantId, because a
-- cross-tenant conflict would reveal another tenant's row. The primary key omits
-- it, safely: the id is always generated by the service (a random UUID for an
-- email request, a cuid otherwise) and never taken from a caller, so there is no
-- conflict anyone can provoke.
