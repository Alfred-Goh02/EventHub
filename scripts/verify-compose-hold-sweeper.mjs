/**
 * Asserts that the COMPOSE STACK returns an expired seat hold by itself.
 *
 * Every other sweeper verifier starts a sweeper of its own with `--once`, so each
 * one proves that the sweep works and none proves that anything runs it. Nothing
 * did. Ticketing's compose container runs `node dist/index.js`, which never
 * imports the sweeper, while the comment above its environment said "the sweeper
 * and reconciler run inside this process" and it was handed SWEEPER_BATCH_SIZE and
 * SWEEPER_INTERVAL_MS that nothing in it read. Measured on the running stack before
 * the fix: a hold that expired at seed time was still HELD 30 s later, its seats
 * still held; and one verifier leftover had sat HELD six days past its expiry.
 * Every abandoned checkout took its seats out of inventory for good, and the
 * symptom is "sold out" on an event that is not.
 *
 * So this verifier starts NOTHING. It takes seats, lets their hold lapse, waits,
 * and asserts the stack gave them back:
 *
 *   - CONTROL, before waiting: the seats really are held. A seat that was never
 *     taken is also available, so "available afterwards" alone proves nothing.
 *   - the reservation is EXPIRED and its seats moved from held to remaining,
 *     exactly once;
 *   - a `reservation.expired` outbox message exists for THIS reservation. Only the
 *     sweeper writes one, so this is the proof that the sweeper did it rather than
 *     some other path freeing the seats;
 *   - a hold that has NOT expired is left alone, so a pass cannot come from
 *     something that releases everything;
 *   - CONTROL: a `hold-sweeper` connection is open from a container. A verifier
 *     elsewhere on a shared machine can run a sweeper on the host, and that would
 *     sweep this row too; a connection from a container's address is the deployed
 *     one.
 *
 * NO DEPENDENCIES, like the other compose verifiers: the compose CI job installs
 * nothing. Postgres is reached with `docker exec psql`, AS THE APP ROLE with
 * app.tenant_id set, for the writes and the cleanup alike. FORCE row security binds
 * every role but the superuser, and a cleanup outside the tenant the rows were
 * written in deletes nothing and reports success; so the cleanup reports what it
 * DELETED, and requires it.
 *
 * Run (with `docker compose up -d --wait` done): node scripts/verify-compose-hold-sweeper.mjs
 */

import { execFile } from 'node:child_process';
import { randomBytes } from 'node:crypto';

const POSTGRES = process.env['POSTGRES_CONTAINER'] ?? 'eventhub-postgres';
const DATABASE = 'eventhub_ticketing';
const APP_ROLE = 'eventhub_ticketing_app';

/**
 * Compose runs the sweeper every 5 s (SWEEPER_INTERVAL_MS). Six intervals is
 * room for a sweep already in progress, a slow CI runner and the poll step,
 * without letting "eventually" stand in for "never".
 */
const DEADLINE_MS = 30_000;

/** A scratch tenant per run: nothing this verifier reads or deletes can be anyone else's. */
const RUN = randomBytes(4).toString('hex');
const TENANT = `tenant_sweepprobe_${RUN}`;
const EVENT_ID = `sweepprobe_${RUN}_evt`;
const TICKET_TYPE_ID = `sweepprobe_${RUN}_tt`;
const LAPSED = `sweepprobe_${RUN}_lapsed`;
const LIVE = `sweepprobe_${RUN}_live`;

const TOTAL = 10;
const LAPSED_QTY = 3;
const LIVE_QTY = 2;
const PRICE_CENTS = 1000;

let failures = 0;
function check(ok, msg) {
  console.log(`    ${ok ? 'ok  ' : 'FAIL'}  ${msg}`);
  if (!ok) {
    failures += 1;
    process.exitCode = 1;
  }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function run(cmd, args, input) {
  return new Promise((resolve, reject) => {
    const child = execFile(cmd, args, { maxBuffer: 16 * 1024 * 1024 }, (err, stdout, stderr) =>
      err ? reject(new Error(`${err.message}\n${stderr}`)) : resolve(stdout.trim()),
    );
    if (input !== undefined) child.stdin.end(input);
  });
}

/**
 * One transaction as the app role, inside this run's tenant. SET LOCAL, not
 * set_config: it returns no row, so the output is only what `sql` selects.
 * Every value interpolated below is generated by this file.
 */
const asTenant = (sql) =>
  run(
    'docker',
    ['exec', '-i', POSTGRES, 'psql', '-U', APP_ROLE, '-d', DATABASE, '-v', 'ON_ERROR_STOP=1', '-q', '-tA'],
    `BEGIN;\nSET LOCAL app.tenant_id = '${TENANT}';\n${sql}\nCOMMIT;\n`,
  );

/** The superuser, for pg_stat_activity only: it sees every backend. */
const asSuperuser = (sql) =>
  run('docker', ['exec', '-i', POSTGRES, 'psql', '-U', 'eventhub', '-d', DATABASE, '-v', 'ON_ERROR_STOP=1', '-q', '-tA', '-c', sql]);

const row = (line) => line.split('|');

const STATE_SQL = `
    SELECT
      (SELECT status FROM "Reservation" WHERE id = '${LAPSED}'),
      (SELECT status FROM "Reservation" WHERE id = '${LIVE}'),
      (SELECT "expiresAt" < now() FROM "Reservation" WHERE id = '${LAPSED}'),
      (SELECT remaining FROM "TicketType" WHERE id = '${TICKET_TYPE_ID}'),
      (SELECT held FROM "TicketType" WHERE id = '${TICKET_TYPE_ID}'),
      (SELECT sold FROM "TicketType" WHERE id = '${TICKET_TYPE_ID}'),
      (SELECT count(*) FROM "OutboxMessage"
        WHERE "eventType" = 'reservation.expired' AND payload->>'reservationId' = '${LAPSED}'),
      (SELECT count(*) FROM "OutboxMessage"
        WHERE "eventType" = 'reservation.expired' AND payload->>'reservationId' = '${LIVE}');`;

function parseState(out) {
  const [lapsed, live, lapsedIsPast, remaining, held, sold, lapsedMsgs, liveMsgs] = row(out);
  return {
    lapsed,
    live,
    lapsedIsPast: lapsedIsPast === 't',
    remaining: Number(remaining),
    held: Number(held),
    sold: Number(sold),
    lapsedMsgs: Number(lapsedMsgs),
    liveMsgs: Number(liveMsgs),
  };
}

const state = async () => parseState(await asTenant(STATE_SQL));

/**
 * Which containers hold a `hold-sweeper` connection, by address.
 *
 * The sweeper names its pool, so pg_stat_activity says which backends are its;
 * the container addresses come from the running stack rather than a list here.
 * A sweeper started on the host connects from the gateway, which is no
 * container's address.
 */
async function sweeperContainers() {
  const addrs = (
    await asSuperuser(
      `SELECT DISTINCT host(client_addr) FROM pg_stat_activity
        WHERE application_name = 'hold-sweeper' AND client_addr IS NOT NULL`,
    )
  )
    .split('\n')
    .filter(Boolean);
  const ids = (await run('docker', ['ps', '-q'])).split(/\s+/).filter(Boolean);
  const byAddr = new Map();
  for (const line of (
    await run('docker', ['inspect', '-f', '{{.Name}}|{{range .NetworkSettings.Networks}}{{.IPAddress}} {{end}}', ...ids])
  ).split('\n')) {
    const [name, ips] = line.split('|');
    for (const ip of (ips ?? '').trim().split(/\s+/).filter(Boolean)) byAddr.set(ip, name.replace(/^\//, ''));
  }
  return { addrs, containers: addrs.map((a) => byAddr.get(a)).filter(Boolean) };
}

/**
 * Seeds the holds and reads them back in the same transaction.
 *
 * The lapsed hold is past its expiry the moment it is committed, and the running
 * sweeper can take it before a separate read: CI once read it EXPIRED with its
 * seats already back, and failed the fixture check on a stack that worked. Read
 * inside the seeding transaction, the answer is what was seeded, because the
 * sweeper cannot see an uncommitted row.
 */
async function seed() {
  const out = await asTenant(`
    INSERT INTO "EventProjection"
      (id, "tenantId", title, slug, status, capacity, "startsAt", "endsAt", "organiserId", "sourceVersion", "updatedAt")
    VALUES ('${EVENT_ID}', '${TENANT}', 'Sweep probe', 'sweep-probe-${RUN}', 'PUBLISHED', ${TOTAL},
            now() + interval '30 days', now() + interval '31 days', 'u_sweepprobe', 1, now());
    INSERT INTO "TicketType"
      (id, "tenantId", "eventId", name, "priceCents", total, remaining, held, sold, "updatedAt")
    VALUES ('${TICKET_TYPE_ID}', '${TENANT}', '${EVENT_ID}', 'General', ${PRICE_CENTS},
            ${TOTAL}, ${TOTAL - LAPSED_QTY - LIVE_QTY}, ${LAPSED_QTY + LIVE_QTY}, 0, now());
    INSERT INTO "Reservation" (id, "tenantId", "eventId", "userId", status, "expiresAt", "updatedAt")
    VALUES ('${LAPSED}', '${TENANT}', '${EVENT_ID}', 'u_sweepprobe', 'HELD', now() - interval '1 minute', now()),
           ('${LIVE}',   '${TENANT}', '${EVENT_ID}', 'u_sweepprobe', 'HELD', now() + interval '1 hour',   now());
    INSERT INTO "ReservationItem" (id, "tenantId", "reservationId", "ticketTypeId", quantity, "unitPriceCents")
    VALUES ('${LAPSED}_i', '${TENANT}', '${LAPSED}', '${TICKET_TYPE_ID}', ${LAPSED_QTY}, ${PRICE_CENTS}),
           ('${LIVE}_i',   '${TENANT}', '${LIVE}',   '${TICKET_TYPE_ID}', ${LIVE_QTY},   ${PRICE_CENTS});
    ${STATE_SQL}`);
  return parseState(out);
}

/**
 * Children first. Each DELETE counts what it removed, and the count left is
 * asked afterwards in the same tenant: "0 deleted, 0 left" is the bug this is
 * written against, so the deleted count is the control.
 */
async function cleanup() {
  // A data-modifying CTE has to be at the top level, and the foreign keys are
  // checked per statement, so: one statement per layer, children first.
  const out = await asTenant(`
    WITH o AS (DELETE FROM "OutboxMessage" WHERE "aggregateId" = '${EVENT_ID}' RETURNING 1),
         i AS (DELETE FROM "ReservationItem" WHERE "reservationId" IN ('${LAPSED}', '${LIVE}') RETURNING 1)
    SELECT (SELECT count(*) FROM o), (SELECT count(*) FROM i);
    WITH r AS (DELETE FROM "Reservation" WHERE id IN ('${LAPSED}', '${LIVE}') RETURNING 1),
         t AS (DELETE FROM "TicketType" WHERE id = '${TICKET_TYPE_ID}' RETURNING 1)
    SELECT (SELECT count(*) FROM r), (SELECT count(*) FROM t);
    WITH e AS (DELETE FROM "EventProjection" WHERE id = '${EVENT_ID}' RETURNING 1)
    SELECT count(*) FROM e;
    SELECT (SELECT count(*) FROM "OutboxMessage" WHERE "tenantId" = '${TENANT}')
         + (SELECT count(*) FROM "ReservationItem" WHERE "tenantId" = '${TENANT}')
         + (SELECT count(*) FROM "Reservation" WHERE "tenantId" = '${TENANT}')
         + (SELECT count(*) FROM "TicketType" WHERE "tenantId" = '${TENANT}')
         + (SELECT count(*) FROM "EventProjection" WHERE "tenantId" = '${TENANT}');`);
  const lines = out.split('\n');
  const [outbox, items] = row(lines[0]).map(Number);
  const [reservations, ticketTypes] = row(lines[1]).map(Number);
  const events = Number(lines[2]);
  const left = Number(lines[3]);
  const deleted = outbox + items + reservations + ticketTypes + events;
  console.log(
    `  cleanup: ${deleted} deleted (outbox ${outbox}, items ${items}, reservations ${reservations}, ` +
      `ticket types ${ticketTypes}, events ${events}), ${left} left`,
  );
  // Six seeded rows, plus the release message if the sweep happened.
  check(deleted >= 6, `CONTROL: the cleanup deleted this run's rows (${deleted}, at least 6 seeded)`);
  check(left === 0, `nothing of tenant ${TENANT} is left behind (${left})`);
}

async function main() {
  console.log(`  scratch tenant ${TENANT}`);

  const sweepers = await sweeperContainers();
  check(
    sweepers.containers.length > 0,
    `CONTROL: a hold-sweeper connection is open from a container ` +
      `(${sweepers.containers.join(', ') || 'none'}; hold-sweeper addresses: ${sweepers.addrs.join(', ') || 'none'})`,
  );

  try {
    const before = await seed();

    console.log('');
    console.log('  before: the seats are taken');
    check(before.lapsed === 'HELD' && before.lapsedIsPast, `the lapsed hold is HELD and past its expiry (${before.lapsed}, past=${before.lapsedIsPast})`);
    check(
      before.remaining === TOTAL - LAPSED_QTY - LIVE_QTY && before.held === LAPSED_QTY + LIVE_QTY,
      `CONTROL: its seats are out of inventory (remaining=${before.remaining}, held=${before.held})`,
    );

    console.log('');
    console.log(`  waiting up to ${DEADLINE_MS / 1000}s for the stack to return them; this script runs no sweeper`);
    const started = Date.now();
    let after = before;
    while (Date.now() - started < DEADLINE_MS) {
      await sleep(500);
      after = await state();
      if (after.lapsed !== 'HELD') break;
    }
    const waited = ((Date.now() - started) / 1000).toFixed(1);

    check(
      after.lapsed === 'EXPIRED',
      after.lapsed === 'EXPIRED'
        ? `the lapsed hold was EXPIRED after ${waited}s`
        : `the lapsed hold is still ${after.lapsed} after ${waited}s: nothing in the running stack sweeps expired holds`,
    );
    check(
      after.remaining === TOTAL - LIVE_QTY && after.held === LIVE_QTY && after.sold === 0,
      `its ${LAPSED_QTY} seats went back exactly once (remaining ${before.remaining} -> ${after.remaining}, held ${before.held} -> ${after.held})`,
    );
    check(after.remaining + after.held + after.sold === TOTAL, `remaining + held + sold is still ${TOTAL}`);
    check(
      after.lapsedMsgs === 1,
      `CONTROL: exactly one reservation.expired message for it, which only the sweeper writes (${after.lapsedMsgs})`,
    );
    check(after.live === 'HELD' && after.liveMsgs === 0, `a hold that has not expired was left alone (${after.live}, ${after.liveMsgs} messages)`);
  } finally {
    console.log('');
    await cleanup();
  }

  console.log('');
  if (failures > 0) {
    console.error(`${failures} check(s) failed. Is the ticketing-sweeper container running? docker compose ps ticketing-sweeper`);
    return;
  }
  console.log('the compose stack returns an expired hold on its own, and only the expired one');
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
